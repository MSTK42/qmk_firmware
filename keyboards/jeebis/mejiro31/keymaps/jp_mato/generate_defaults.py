#!/usr/bin/env python3
"""Generate editable defaults from the previously verified author transcription."""
import argparse
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
KB = HERE.parents[1]
OUTPUT = KB / 'qmk/defaults_mato.h'
PHYSICAL = list(range(1, 6)) + list(range(6, 11)) + list(range(13, 18)) + list(range(18, 23)) + [40, 41, 42, 43]
SYMBOLS = {
    'JP_MINS': 'KC_MINS', 'JP_COMM': 'KC_COMM', 'JP_SLSH': 'KC_SLSH',
    'JP_DOT': 'KC_DOT', 'JP_BSLS': 'KC_BSLS', 'JP_YEN': 'KC_INT3',
    'JP_COLN': 'KC_COLN', 'JP_SCLN': 'KC_SCLN', 'JP_AT': 'KC_AT',
    'JP_LBRC': 'KC_LBRC', 'JP_RBRC': 'KC_RBRC', 'JP_CIRC': 'KC_CIRC',
}
SPECIAL = {
    'HOLD_MO2_TAP_ZKHK': ('MJI_IME', 'MO(2)'),
    'HOLD_MO3_TAP_SPACE': ('KC_SPC', 'MO(3)'),
    'HOLD_MO4_TAP_ENTER': ('KC_ENT', 'MO(4)'),
    'MO1': ('KC_NO', 'MO(1)'), 'SHIFT': ('KC_NO', 'KC_LSFT'),
    'SHIFT_SPACE': ('KC_SPC', 'KC_LSFT'), 'SHIFT_ENTER': ('KC_ENT', 'KC_LSFT'),
    'BLANK': ('KC_NO', 'KC_NO'), 'TRANSPARENT': ('KC_TRNS', 'KC_TRNS'),
    **{f'CTRL_{key}': (f'LCTL(KC_{key})', 'KC_NO') for key in 'ZXCV'},
}
MODS = {'SHIFT': 'KC_LSFT', 'CTRL': 'KC_LCTL', 'ALT': 'KC_LALT', 'GUI': 'KC_LGUI'}
COMBOS = {frozenset(pair): logical for pair, logical in [
    ((1, 13), 24), ((2, 14), 25), ((3, 15), 26), ((4, 16), 27),
    ((7, 19), 33), ((8, 20), 34), ((9, 21), 35), ((10, 22), 36),
]}

def render():
    source = json.loads((HERE / 'mato-source.json').read_text(encoding='utf-8'))
    positions = dict(zip(source['positions'], PHYSICAL, strict=True))
    maps = [['KC_NO'] * 48 for _ in range(16)]
    for layer in source['layers']:
        lid = layer['id']
        for name, key in layer['keys'].items():
            tap, hold = SPECIAL.get(key, (SYMBOLS.get(key, key), 'KC_NO'))
            p = positions[name]
            maps[lid][p], maps[lid + 6][p] = tap, hold
        # Seven Mejiro31-only controls are explicit editable bindings.
        for p, key in {0: 'KC_ESC', 12: 'KC_TAB', 11: 'KC_DEL', 23: 'KC_BSPC',
                       28: 'KC_LNG2', 29: 'MJI_MODE', 30: 'KC_LNG1'}.items():
            maps[lid][p] = key
        if lid in (0, 1):
            for combo in source['modifier_combos']:
                pair = frozenset(positions[name] for name in combo['keys'])
                maps[lid + 6][COMBOS[pair]] = MODS[combo['modifier']]
    # Preserve the current upstream steno bindings, with a plain mode button.
    defaults = (KB / 'qmk/defaults.h').read_text(encoding='utf-8')
    block = defaults.split('#define MJI_DEFAULT_STENO(KEY)', 1)[1].split('\n}\n', 1)[0]
    pairs = re.findall(r'KEY\(([^,]+),\s*([^\n]+?)\)(?=,|\s*})', block)
    if len(pairs) != 48:
        raise ValueError(f'Expected 48 upstream Steno bindings, got {len(pairs)}')
    for p, (tap, hold) in enumerate(pairs):
        maps[5][p], maps[11][p] = tap.strip(), hold.strip()
    maps[11][29] = 'KC_NO'
    lines = ['// SPDX-License-Identifier: GPL-2.0-or-later',
             '// Generated by keymaps/jp_mato/generate_defaults.py; edit mato-source.json.',
             '// Layers: base, consonants, numbers, navigation, function, upstream Steno.',
             '#pragma once', 'const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {']
    for lid, values in enumerate(maps):
        lines.append(f'    [{lid}] = {{')
        for row in range(4):
            lines.append('        { ' + ', '.join(values[row * 12:(row + 1) * 12]) + ' },')
        lines.append('    },')
    return '\n'.join(lines + ['};', ''])

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != expected:
            raise SystemExit('mato defaults differ from the verified source; regenerate them')
        print('mato defaults match the author source and current upstream Steno map')
    else:
        OUTPUT.write_text(expected, encoding='utf-8', newline='\n')
